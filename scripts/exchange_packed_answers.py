def capture(args):
    """Offline: both arms' exact answer request bodies for each of the 73 retrieval runs. No generation."""
    import retrieval_harness as harness
    output = args.output.absolute()
    require(output.is_relative_to(ROOT / ".build"), "output_outside_build")
    reference = args.reference.absolute()
    ref_declaration, ref_runs = rc.reference_runs(reference)
    baseline, baseline_rows = {}, {}
    if args.baseline_captures:
        document = json.loads(args.baseline_captures.read_text())
        # Rows of this driver carry an arm; the reader comparison's rows (one arm) do not.
        baseline_rows = {(row["cohort"], row["question_id"]): row for row in document["rows"]
                         if row.get("arm", BASELINE) == BASELINE}
        baseline = {key: row["request_sha256"] for key, row in baseline_rows.items()}
    # A baseline other than the step 3 declaration's ordinary Send is checked against the same arm's
    # recorded delivery in --baseline-captures instead.
    require(BASELINE == "ordinary_send" or baseline_rows, "baseline_captures_required")
    plan = v4v.cohorts()
    frozen = v4v.frozen_inputs(args.dataset, plan)
    replay.private_directory(output)
    requests = output / "requests"
    replay.private_directory(requests)
    cache_root = output / "harness"
    replay.private_directory(cache_root)
    binary, implementation = harness.compile_harness(cache_root)
    endpoint = harness.OfflineEndpoint(args.tokenizer, 0).start()
    rows = []
    try:
        with tempfile.TemporaryDirectory(prefix="boros-exchange-capture-", dir=output) as scratch_name:
            scratch = Path(scratch_name)
            os.chmod(scratch, 0o700)
            for cohort in COHORTS:
                cases, _arm = plan[cohort]
                for qid, run, strategy, _policy in cases:
                    index, entry = ref_runs[(cohort, qid)]
                    history, document, _ = frozen[(qid, run)]
                    require(v5plan.e_digest(document) == entry["runner_input_sha256"], "runner_input_mismatch")
                    require(v4v.gold_arm(cohort, strategy) == "ordinary_send" == entry["declared_gold_arm"], "arm_mismatch")
                    directory = requests / case_name(cohort, qid)
                    require(not directory.exists(), "capture_exists")
                    replay.private_directory(directory)
                    hybrid = [attempt for attempt in document["attempts"] if attempt["strategy"] == "hybrid"][0]
                    configuration = dict(document["configuration"], endpoint=endpoint.url)
                    base = {"version": 1, "cache_directory": str(cache_root / "stores" / v5plan.e_digest(document)),
                            "events": document["events"], "configuration": configuration,
                            "question": {key: hybrid[key] for key in ("project_id", "conversation_key", "prompt",
                                                                      "question_time")},
                            "arms": list(ARMS), "declared_source_ids": None, "capture_directory": str(directory)}
                    selection = harness.run_process(binary, "select", base, scratch, "capture")
                    attempts = {item.get("arm"): item for item in selection.get("attempts") or []}
                    sizes = {event["id"]: len(event["text"].encode()) for event in document["events"]}
                    for arm in ARMS:
                        item = attempts.get(arm) or {}
                        ranges = v5plan.delivered_ranges(item.get("recent_source_ids") or [], item.get("evidence") or [],
                                                         sizes)
                        row = {"cohort": cohort, "question_id": qid, "arm": arm, "reference_run": index,
                               "runner_input_sha256": entry["runner_input_sha256"],
                               "process_failure": selection.get("process_failure"), "failure": item.get("failure"),
                               "preparation_completed": bool(item.get("preparation_completed")),
                               "runner_started": bool(item.get("runner_started")),
                               "context_framing": item.get("context_framing"),
                               "delivered_ranges_sha256": replay.ranges_digest(ranges),
                               "delivered_recent": len(item.get("recent_source_ids") or []),
                               "delivered_excerpts": len(item.get("evidence") or []),
                               "harness_prompt_tokens": item.get("prompt_tokens"),
                               "request_sha256": item.get("request_sha256"), "request_bytes": item.get("request_bytes"),
                               "maximum_output": entry["maximum_output"], "question_type": entry["question_type"],
                               "abstention": entry["abstention"], "citation_labels": item.get("citation_labels"),
                               **replay.gold_delivery(history, ranges)}
                        if arm == BASELINE and BASELINE == "ordinary_send":
                            row["reference"] = "step3_declaration"
                            row["delivery_matches_reference"] = row["delivered_ranges_sha256"] \
                                == entry["declared_delivered_ranges_sha256"]
                            row["gold_matches_reference"] = row["gold_delivery"] == entry["declared_gold_delivery"]
                            if baseline:
                                row["request_matches_baseline"] = baseline.get((cohort, qid)) == row["request_sha256"]
                        elif arm == BASELINE:
                            # The baseline's delivery and gold class must reproduce the earlier capture
                            # of the same arm; its request body differs in ingestion identifiers only.
                            previous = baseline_rows.get((cohort, qid)) or {}
                            row["reference"] = "baseline_captures:" + BASELINE
                            row["delivery_matches_reference"] = row["delivered_ranges_sha256"] \
                                == previous.get("delivered_ranges_sha256")
                            row["gold_matches_reference"] = row["gold_delivery"] == previous.get("gold_delivery") \
                                and row["gold_turns_whole"] == previous.get("gold_turns_whole")
                            row["request_matches_baseline"] = baseline.get((cohort, qid)) == row["request_sha256"]
                        body_path = directory / (arm + ".request.json")
                        if body_path.exists():
                            raw = body_path.read_bytes()
                            row["body_digest_matches"] = replay.digest(raw) == item.get("request_sha256")
                            messages = rc.request_messages(raw)
                            row["message_roles"] = [message["role"] for message in messages]
                        rows.append(row)
                        print(json.dumps({key: row.get(key) for key in (
                            "cohort", "question_id", "arm", "failure", "gold_delivery", "delivery_matches_reference",
                            "request_matches_baseline", "body_digest_matches", "harness_prompt_tokens")}), flush=True)
    finally:
        endpoint.stop()
    require(not any(row["runner_started"] for row in rows), "answer_runner_started")
    manifest = {"version": VERSION, "kind": "exchange-packed-captures", "recorded_at_utc": now(),
                "reference": {"path_name": reference.name, "declaration_sha256":
                              replay.digest((reference / "declaration.json").read_bytes()),
                              "binary_sha256": ref_declaration["binary"]["sha256"]},
                "baseline_captures_sha256": replay.digest(args.baseline_captures.read_bytes())
                if args.baseline_captures else None,
                "harness": implementation, "endpoint_counters": endpoint.counters, "rows": rows,
                "summary": capture_summary(rows)}
    replay.private_write(output / "captures.json", replay.canonical(manifest) + b"\n")
    print(json.dumps({"captures": len(rows), **manifest["summary"],
                      "captures_sha256": replay.digest((output / "captures.json").read_bytes())}))


def capture_summary(rows):
    out = {}
    for arm in ARMS:
        mine = [row for row in rows if row["arm"] == arm]
        tokens = [row["harness_prompt_tokens"] for row in mine if isinstance(row.get("harness_prompt_tokens"), int)]
        out[arm] = {"rows": len(mine),
                    "complete": sum(1 for row in mine if row.get("body_digest_matches") and row["preparation_completed"]),
                    "framing_v4": sum(1 for row in mine if row.get("context_framing") == rc.V4),
                    "gold_delivery": {kind: sum(1 for row in mine if row["gold_delivery"] == kind)
                                      for kind in ("whole", "partial", "none", "no_gold_turns")},
                    "prompt_tokens_median": statistics.median(tokens) if tokens else None,
                    "prompt_tokens_max": max(tokens) if tokens else None}
    baseline = [row for row in rows if row["arm"] == BASELINE]
    out[BASELINE]["delivery_matches_reference"] = sum(1 for row in baseline if row.get("delivery_matches_reference"))
    out[BASELINE]["gold_matches_reference"] = sum(1 for row in baseline if row.get("gold_matches_reference"))
    out[BASELINE]["request_matches_baseline"] = sum(1 for row in baseline if row.get("request_matches_baseline"))
    return out


def load_captures(output: Path):
    manifest = json.loads((output / "captures.json").read_text())
    require(manifest.get("version") == VERSION, "captures_version")
    summary = manifest["summary"]
    require(len(manifest["rows"]) == QUESTIONS * len(ARMS), "captures_not_146")
    for arm in ARMS:
        require(summary[arm]["complete"] == summary[arm]["framing_v4"] == QUESTIONS, "captures_incomplete")
    require(summary[BASELINE]["delivery_matches_reference"] == QUESTIONS, "baseline_does_not_match_reference")
    return manifest


def captured_body(output: Path, row):
    raw = (output / "requests" / case_name(row["cohort"], row["question_id"]) / (row["arm"] + ".request.json")).read_bytes()
    require(replay.digest(raw) == row["request_sha256"], "captured_body_changed")
    return rc.request_messages(raw)


# --------------------------------------------------------------------------- count

def count(args):
    """Free token counts of every captured body on the reader's count endpoint."""
    output = args.output.absolute()
    manifest = load_captures(output)
    token = va.AccessTokens()
    rows = []
    for row in manifest["rows"]:
        url, body = rc.count_request(READER, captured_body(output, row))
        tokens = rc.vg.parse_count(rc.send(READER, url, body, token()))
        rows.append({"cohort": row["cohort"], "question_id": row["question_id"], "arm": row["arm"],
                     "input_tokens": tokens, "max_output_tokens": rc.max_output(READER, row)})
    price = rc.pricing(READER)
    totals = {}
    for arm in ARMS:
        mine = [row for row in rows if row["arm"] == arm]
        worst = sum(price.microusd(row["input_tokens"], row["max_output_tokens"]) for row in mine) * REPLICATES
        totals[arm] = {"input_tokens_per_pass": sum(row["input_tokens"] for row in mine),
                       "input_tokens_median": statistics.median(row["input_tokens"] for row in mine),
                       "worst_case_usd_all_replicates": str(Decimal(worst) / Decimal(10**6))}
    document = {"version": VERSION, "kind": "exchange-packed-counts", "recorded_at_utc": now(),
                "captures_sha256": replay.digest((output / "captures.json").read_bytes()), "rows": rows, "totals": totals}
    replay.private_write(output / "counts.json", replay.canonical(document) + b"\n")
    print(json.dumps({"counts": len(rows), "totals": totals}))


