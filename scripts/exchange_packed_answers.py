"""Answer quality of the P2 ``exchange_packed`` selection against ordinary Send, with a hosted reader.

R1 of the context-diagnostic response (docs/reviews/CONTEXT-DIAGNOSTIC-RESPONSE-20261012.md): the
policy raises development R2 from 50 to 69 of 90 but has no answer-quality evidence. Requested by the
user on October 12, 2026, with Vertex as the evaluation route and no local model. Record:
docs/EXCHANGE-PACKED-ANSWERS.md.

Inputs are the 73 retrieval runs of the step 3 cohorts (retrieval-on-21, preference-27, temporal-25;
the reader comparison's inputs without recent-only-21, whose recent-only strategy has no selection
policy). ``capture`` rebuilds, offline and in one harness process per input, the exact answer request
bodies of both arms: ``ordinary_send`` (the current default, checked against the step 3 declaration's
delivered ranges) and ``exchange_packed``. No answer is generated by ``capture``. Since the October 12
default switch the harness ``ordinary_send`` arm selects ``exchange_packed``, so a rerun of ``capture`` fails
the baseline's reference check; the recorded run captured the earlier v1/16 default.

Reader: ``gemini-3.8-flash`` through vertex_gemini.py with the reader comparison's settings (thinking
level "low", a 2,048-token thinking allowance on the step 3 output limit, no sampling field). Both
arms are answered fresh in the same run, three replicates, interleaved. Judge: the default verdict
judge (gemini_judge.py, prompt set v4) on one blinded set holding both arms.

Commands: ``capture``, ``count`` (free), ``declare``, ``run`` (paid), ``judge-set``, ``score``.

Arms: ``--baseline-arm`` and ``--candidate-arm`` (defaults ``ordinary_send`` and ``exchange_packed``) select
the two harness arms, so the same driver measures a later policy against the current default. A
baseline other than ``ordinary_send`` has no step 3 declaration to check against; its delivery and gold
class are instead checked against the same arm's rows in ``--baseline-captures`` (a previous run of this
driver), which must then be given. ``--promote-minimum-points`` raises the declared promotion threshold
on D (default 0, the October 12 rule); the declaration records it and ``score`` applies the recorded value.
The evidence-allowance run (docs/EVIDENCE-ALLOWANCE.md) used ``exchange_packed`` against ``exchange_wide``
with a 5-point threshold.

Privacy: request bodies, answers and raw responses stay in the private output directory (0700
directories, 0600 files) and are never printed. stdout carries counts, hashes, identifiers and fixed
codes only. The Boros application is unchanged.
"""
