def run(args):
    output = args.output.absolute()
    declaration = json.loads((output / "declaration.json").read_text())
    require(declaration.get("version") == VERSION, "declaration_version")
    manifest = load_captures(output)
    require(replay.digest((output / "captures.json").read_bytes()) == declaration["captures_sha256"], "captures_changed")
    counts_document = json.loads((output / "counts.json").read_text())
    require(replay.digest((output / "counts.json").read_bytes()) == declaration["counts_sha256"], "counts_changed")
    for name, value in declaration["drivers"].items():
        require(replay.digest((ROOT / "scripts" / name).read_bytes()) == value, "driver_changed")
    counted = {(row["arm"], row["cohort"], row["question_id"]): row for row in counts_document["rows"]}
    rows = {(row["arm"], row["cohort"], row["question_id"]): row for row in manifest["rows"]}
    answers = output / "answers"
    replay.private_directory(answers)
    for arm in ARMS:
        replay.private_directory(answers / arm)
    cap = Decimal(declaration["spending_cap_usd"]) * 10**6
    lock = threading.Lock()
    done = finished_records(output)
    token = va.AccessTokens()
    state = {"spent": sum(record.get("microusd") or 0 for record in done.values()), "stopped": None}
    price = rc.pricing(READER)

    def append(record):
        with open(output / "ledger.jsonl", "a") as handle:
            handle.write(json.dumps(record, sort_keys=True) + "\n")

    def work(index):
        job = declaration["jobs"][index]
        key = (job["arm"], job["cohort"], job["question_id"])
        row = rows[key]
        worst = price.microusd(counted[key]["input_tokens"], rc.max_output(READER, row))
        with lock:
            if state["stopped"] or state["spent"] + worst > cap:
                state["stopped"] = state["stopped"] or "cap_reached"
                return
            state["spent"] += worst  # reserved; settled below
            append({"job": index, "state": "started", "at": now()})
        url, body = rc.generation_request(READER, captured_body(output, row), row)
        failure, raw, tries = None, None, 0
        while True:
            tries += 1
            started = time.monotonic()
            try:
                raw = rc.send(READER, url, body, token())
                failure = None
            except va.VertexError as error:
                failure = str(error)
            if failure in rc.RETRYABLE and tries <= len(rc.RETRY_DELAYS):
                time.sleep(rc.RETRY_DELAYS[tries - 1])
                continue
            break
        seconds = time.monotonic() - started
        name = answer_name(job["arm"], job["cohort"], job["question_id"], job["replicate"])
        record = {"job": index, "state": "finished", **job, "tries": tries, "seconds": round(seconds, 3), "at": now()}
        microusd = 0
        if raw is not None:
            text, usage, stop, failure = rc.parse(READER, raw)
            replay.private_write(answers / (name + ".response.json"), raw)
            if usage is not None:
                microusd = price.microusd(usage["input_tokens"], usage["output_tokens"])
                record.update(input_tokens=usage["input_tokens"], output_tokens=usage["output_tokens"],
                              reasoning_tokens=usage["reasoning_tokens"])
            if text is not None:
                replay.private_write(answers / (name + ".txt"), text.encode())
                record["answer_sha256"] = replay.digest(text.encode())
            record["stop_reason"] = stop
        record.update(failure=failure, microusd=microusd)
        with lock:
            state["spent"] += microusd - worst
            append(record)
            if failure not in (None, "incomplete_result") and failure.startswith("http_status_4") \
                    and failure != "http_status_429":
                state["stopped"] = "client_error_" + failure
        print(json.dumps({key: record.get(key) for key in ("job", "arm", "cohort", "question_id", "replicate",
                                                          "failure", "seconds", "microusd")}), flush=True)

    pending = [index for index in range(len(declaration["jobs"])) if index not in done]
    with ThreadPoolExecutor(max_workers=declaration["workers"]) as pool:
        list(pool.map(work, pending))
    finished = list(finished_records(output).values())
    print(json.dumps({"finished": len(finished), "jobs": len(declaration["jobs"]), "stopped": state["stopped"],
                      "spent_usd_declared_rate": str(Decimal(sum(record.get("microusd") or 0 for record in finished))
                                                     / 10**6),
                      "failures": sum(1 for record in finished if record.get("failure") not in (None, "incomplete_result")),
                      "incomplete": sum(1 for record in finished if record.get("failure") == "incomplete_result")}))


