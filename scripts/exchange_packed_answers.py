def answered(output: Path):
    """Every declared job with its answer text (or None), capture row and ledger record."""
    declaration = json.loads((output / "declaration.json").read_text())
    manifest = load_captures(output)
    rows = {(row["arm"], row["cohort"], row["question_id"]): row for row in manifest["rows"]}
    records = finished_records(output)
    out = []
    for index, job in enumerate(declaration["jobs"]):
        record = records.get(index) or {}
        path = output / "answers" / (answer_name(job["arm"], job["cohort"], job["question_id"], job["replicate"]) + ".txt")
        answer = path.read_text() if record and path.exists() else None
        if answer is not None:
            require(replay.digest(answer.encode()) == record.get("answer_sha256"), "answer_changed")
        out.append({**job, "row_index": index, "answer": answer, "record": record,
                    "capture": rows[(job["arm"], job["cohort"], job["question_id"])]})
    return declaration, out


def judge_set(args):
    """One blinded verdict set holding every answer of both arms, in a seeded order. No judge call."""
    import judge_calibration as jc
    output = args.output.absolute()
    _declaration, entries = answered(output)
    plan = v4v.cohorts()
    frozen = v4v.frozen_inputs(args.dataset, plan)
    sources = {(qid, cohort): run for cohort in COHORTS for qid, run, _, _ in plan[cohort][0]}
    seed = replay.digest((output / "declaration.json").read_bytes())
    records = jc.load_dataset(args.dataset)
    candidates = []
    for entry in entries:
        if entry["answer"] is None:
            continue
        history, _document, _ = frozen[(entry["question_id"], sources[(entry["question_id"], entry["cohort"])])]
        arm = f"{entry['arm']}:r{entry['replicate']}"
        candidate = jc.new_candidate(run=f"exchange-packed-answers-{entry['cohort']}", run_family="exchange-packed-answers",
                                     arm=arm, question_id=entry["question_id"], answer_model=READER,
                                     operational_complete=True, answer_sha256=replay.digest(entry["answer"].encode()))
        jc.attach_question(candidate, records)
        require(candidate["reference"] is not None, "question_missing_from_dataset")
        candidate["scrub_ids"].update(event["id"] for event in history["events"])
        jc.verify_answer(candidate, entry["answer"])
        candidates.append((jc.rank(seed, str(entry["row_index"]), entry["question_id"], arm), entry, candidate))
    candidates.sort(key=lambda value: value[0])
    require(len(candidates) <= 999, "judge_set_too_large")
    items, keys = [], []
    for position, (_rank, entry, candidate) in enumerate(candidates, start=1):
        item, replaced = jc.blind_item(candidate, f"item-{position:03d}")
        items.append(item)
        keys.append({"item_id": item["item_id"], "row_index": entry["row_index"], "run": candidate["run"],
                     "arm": entry["arm"], "replicate": entry["replicate"], "cohort": entry["cohort"],
                     "question_id": entry["question_id"], "abstention": bool(candidate["abstention"]),
                     "question_type": candidate["question_type"], "answer_sha256": candidate["answer_sha256"],
                     "item_sha256": replay.digest(replay.canonical(item)), "identifier_substitutions": replaced})
    set_id = "jep-" + replay.digest(replay.canonical({"seed": seed, "keys": [
        [key["row_index"], key["answer_sha256"]] for key in keys]}))[:16]
    items_document = {"format": jc.ITEMS_FORMAT, "set_id": set_id, "items": items}
    key_document = {"format": replay.JUDGE_KEY_FORMAT, "set_id": set_id, "seed": seed, "items": keys}
    require(not jc.blinding_violations(items_document, key_document), "blinding_violation")
    manifest = replay.write_judge_set(output / "judge-set", items_document, key_document, "exchange-packed-answers", seed)
    print(json.dumps({"set_id": manifest["set_id"], "items": manifest["item_count"], "items_sha256": manifest["items_sha256"],
                      "arms": {arm: sum(1 for key in keys if key["arm"] == arm) for arm in ARMS},
                      "identifier_substitutions": manifest["identifier_substitutions"],
                      "identity_mention_items": len(manifest["identity_mention_items"])}))


# --------------------------------------------------------------------------- statistics

def sign_test(better, worse):
    n, k = better + worse, min(better, worse)
    return min(1.0, 2 * sum(math.comb(n, i) for i in range(k + 1)) / 2 ** n) if n else 1.0


def bootstrap_interval(differences, seed, resamples=BOOTSTRAP_RESAMPLES):
    """95 percent percentile interval of the mean of paired per-question differences."""
    require(differences, "no_differences")
    generator = random.Random(seed)
    n = len(differences)
    means = sorted(sum(differences[generator.randrange(n)] for _ in range(n)) / n for _ in range(resamples))
    return means[int(0.025 * resamples)], means[int(math.ceil(0.975 * resamples)) - 1]


def paired(per_question, questions, seed):
    """Mean accept rates (points), D, its interval and the sign test over `questions`."""
    base = [per_question[question][BASELINE] for question in questions]
    cand = [per_question[question][CANDIDATE] for question in questions]
    differences = [100 * (c - b) for b, c in zip(base, cand)]
    low, high = bootstrap_interval(differences, seed)
    better = sum(1 for value in differences if value > 0)
    worse = sum(1 for value in differences if value < 0)
    return {"questions": len(questions), "baseline_percent": round(100 * sum(base) / len(base), 1),
            "candidate_percent": round(100 * sum(cand) / len(cand), 1),
            "difference_points": round(sum(differences) / len(differences), 1),
            "interval_points": [round(low, 1), round(high, 1)], "better": better, "worse": worse,
            "tie": len(questions) - better - worse, "sign_test_p": round(sign_test(better, worse), 4)}


def decide(overall, cohorts, promote_minimum_points=0.0):
    """The pre-declared outcome (decision_rule) at the declared promotion threshold."""
    difference, (low, _high) = overall["difference_points"], overall["interval_points"]
    lever = difference >= 5 and low > 0
    promote = difference >= promote_minimum_points and low >= -2 \
        and all(value["difference_points"] >= -5 for value in cohorts.values())
    return {"promote": promote, "retrieval_lever": lever, "promote_minimum_points": promote_minimum_points,
            "outcome": "promote" if promote else "no_default_change"}


def score(args):
    """Joins the judge's labels with the answers: per-question paired comparison. Counts and IDs only."""
    import judge_calibration as jc
    output = args.output.absolute()
    declaration, entries = answered(output)
    key_document = jc.load_json(output / "judge-set" / "key.json")
    labels_document = jc.load_json(args.labels)
    require(labels_document.get("set_id") == key_document["set_id"], "labels_set_mismatch")
    require(labels_document.get("replicates") == 3 and labels_document.get("complete") is True, "labels_incomplete")
    verdicts = {}
    for key in key_document["items"]:
        entry = entries[key["row_index"]]
        require(entry["question_id"] == key["question_id"] and entry["arm"] == key["arm"], "key_row_mismatch")
        labels = [value.get("verdict") for value in labels_document["labels"].get(key["item_id"], [{}, {}, {}])]
        verdicts[key["row_index"]] = replay.majority_of_three(labels)
    per_question, samples, gold, declines = {}, {}, {}, {}
    for entry in entries:
        question = case_name(entry["cohort"], entry["question_id"])
        verdict = verdicts.get(entry["row_index"])
        samples.setdefault(question, {}).setdefault(entry["arm"], []).append(verdict)
        gold.setdefault(question, {})[entry["arm"]] = entry["capture"]["gold_delivery"]
        if entry["answer"] is not None:
            outcome = v5plan.decline_outcome(entry["answer"])["outcome"]
            declines.setdefault(entry["arm"], []).append((v5plan.is_decline(outcome), entry["capture"]["gold_delivery"],
                                                          bool(entry["capture"]["abstention"])))
    for question, arms in samples.items():
        per_question[question] = {arm: sum(1 for value in values if value == "accept") / REPLICATES
                                  for arm, values in arms.items()}
    seed = replay.digest((output / "declaration.json").read_bytes())
    counted = sorted(question for question in per_question if not question.endswith(tuple(EXCLUDED_FROM_COUNTS)))
    overall = paired(per_question, counted, seed)
    cohorts = {cohort: paired(per_question, [q for q in counted if q.startswith(cohort + "--")], seed)
               for cohort in COHORTS}
    transitions = {}
    for question in counted:
        before, after = gold[question][BASELINE], gold[question][CANDIDATE]
        group = ("same_delivery" if before == after else
                 "gained_whole" if after == "whole" else "lost_whole" if before == "whole" else "changed_not_whole")
        transitions.setdefault(group, []).append(question)
    by_transition = {group: paired(per_question, questions, seed) for group, questions in sorted(transitions.items())}
    decline_table = {arm: {"answers": len(values), "declines": sum(1 for value in values if value[0]),
                           "false_declines_gold_whole": sum(1 for value in values if value[0] and value[1] == "whole"
                                                            and not value[2])}
                     for arm, values in declines.items()}
    verdict_counts = {arm: {label: sum(1 for entry in entries if entry["arm"] == arm
                                       and verdicts.get(entry["row_index"]) == label)
                            for label in ("accept", "reject", "unknown")} for arm in ARMS}
    verdict_counts["missing"] = sum(1 for entry in entries if entry["row_index"] not in verdicts)
    tokens = {arm: statistics.median(entry["record"]["input_tokens"] for entry in entries
                                     if entry["arm"] == arm and entry["record"].get("input_tokens")) for arm in ARMS}
    document = {"version": VERSION, "kind": "exchange-packed-score", "recorded_at_utc": now(),
                "set_id": key_document["set_id"], "judge": labels_document.get("judge"),
                "labels_declaration_sha256": labels_document.get("declaration_sha256"),
                "decision_rule": declaration["decision_rule"], "overall": overall, "cohorts": cohorts,
                "decision": decide(overall, cohorts, float(declaration["decision_rule"].get("promote_minimum_points", 0))),
                "by_gold_transition": by_transition,
                "gold_delivery": {arm: {kind: sum(1 for q in counted if gold[q][arm] == kind)
                                        for kind in ("whole", "partial", "none", "no_gold_turns")} for arm in ARMS},
                "declines": decline_table, "verdicts": verdict_counts, "median_input_tokens": tokens,
                "excluded": {question: {arm: samples[question][arm] for arm in ARMS}
                             for question in per_question if question.endswith(tuple(EXCLUDED_FROM_COUNTS))},
                "per_question": {question: {arm: [per_question[question][arm], gold[question][arm]] for arm in ARMS}
                                 for question in sorted(per_question)}}
    replay.private_write(output / "score.json", replay.canonical(document) + b"\n")
    print(json.dumps({key: document[key] for key in ("overall", "cohorts", "decision", "by_gold_transition",
                                                      "gold_delivery", "declines", "verdicts", "median_input_tokens")},
                     indent=1))


