def latest_records(output: Path):
    out = {}
    for line in (output / "ledger.jsonl").read_text().splitlines():
        record = json.loads(line)
        if record["state"] == "finished":
            out[record["job"]] = record
    return out


def answered_rows(output: Path, dataset: Path, qwen_runs):
    """Every answer to measure: (reader, replicate label, cohort, question ID, answer or None, label map, record).
    Qwen answers come from the V4 arm of each reference run directory in `qwen_runs`."""
    declaration = json.loads((output / "declaration.json").read_text())
    manifest = load_captures(output)
    rows = {(row["cohort"], row["question_id"]): row for row in manifest["rows"]}
    records = latest_records(output)
    out = []
    for index, job in enumerate(declaration["jobs"]):
        record = records.get(index)
        path = output / "answers" / (answer_name(job["model"], job["cohort"], job["question_id"], job["replicate"]) + ".txt")
        answer = path.read_text() if record and path.exists() else None
        row = rows[(job["cohort"], job["question_id"])]
        out.append({"reader": job["model"], "replicate": f"r{job['replicate']}", "cohort": job["cohort"],
                    "question_id": job["question_id"], "answer": answer, "label_map": row["citation_labels"],
                    "record": record or {}, "status": "measured" if answer is not None else "not_answered"})
    for run_dir in qwen_runs:
        run_dir = run_dir.absolute()
        reference = json.loads((run_dir / "declaration.json").read_text())
        ledger_rows = replay.ledger(run_dir)
        for index, entry in enumerate(reference["runs"]):
            if entry["arm"] != "v4-default" or (entry["cohort"], entry["question_id"]) not in rows:
                continue
            row = rows[(entry["cohort"], entry["question_id"])]
            require(entry["runner_input_sha256"] == row["runner_input_sha256"], "qwen_input_mismatch")
            report, item, answer = native_answer(run_dir, ledger_rows, index, entry["attempt"])
            same_delivery = item is not None and replay.ranges_digest(item.get("delivered_ranges")) \
                == entry["declared_delivered_ranges_sha256"]
            usage = (item or {}).get("provider_usage") or {}
            out.append({"reader": "qwen-local", "replicate": reference["version"], "cohort": entry["cohort"],
                        "question_id": entry["question_id"], "answer": answer,
                        "label_map": (item or {}).get("citation_labels"),
                        "record": {"seconds": ((item or {}).get("provider_milliseconds") or 0) / 1000 or None,
                                   "input_tokens": usage.get("promptTokens"), "output_tokens": usage.get("completionTokens"),
                                   "failure": (item or {}).get("failure"), "delivery_as_declared": same_delivery,
                                   "framing": (item or {}).get("context_framing")},
                        "status": "measured" if answer is not None else "not_answered"})
    return declaration, manifest, out


def measure_rows(output: Path, dataset: Path, qwen_runs):
    declaration, manifest, answered = answered_rows(output, dataset, qwen_runs)
    plan = v4v.cohorts()
    frozen = v4v.frozen_inputs(dataset, plan)
    sources = {(qid, cohort): run for cohort in COHORT_ORDER for qid, run, _, _ in plan[cohort][0]}
    rows = {(row["cohort"], row["question_id"]): row for row in manifest["rows"]}
    measured = []
    for entry in answered:
        captured = rows[(entry["cohort"], entry["question_id"])]
        history, document, _ = frozen[(entry["question_id"], sources[(entry["question_id"], entry["cohort"])])]
        probe = history["episodes"][0]
        out = {key: entry[key] for key in ("reader", "replicate", "cohort", "question_id", "status")}
        out.update(question_type=captured["question_type"], abstention=captured["abstention"],
                   declared_gold_delivery=captured["declared_gold_delivery"], record=entry["record"])
        answer = entry["answer"]
        if answer is not None:
            known = [event["id"] for event in document["events"]]
            values = replay.measure_answer(answer, probe["prompt"], probe["answer"], known, entry["label_map"])
            base_outcome = values.pop("outcome")
            values.pop("decline_opening", None)
            out.update(base_outcome=base_outcome, answer_sha256=replay.digest(answer.encode()), **values,
                       **v5plan.decline_outcome(answer), **v5plan.cites_gold(answer, history, entry["label_map"]),
                       **v4v.self_contradiction(answer, probe["answer"], bool(probe["abstention"])))
            out["decline_class"] = replay.decline_class(out["outcome"], out["abstention"], out["declared_gold_delivery"])
        measured.append(out)
    return declaration, measured, answered, frozen, sources


SUBSETS = {
    "answerable_gold_whole": lambda row: not row["abstention"] and row["declared_gold_delivery"] == "whole",
    "answerable_gold_partial": lambda row: not row["abstention"] and row["declared_gold_delivery"] == "partial",
    "answerable_gold_none": lambda row: not row["abstention"] and row["declared_gold_delivery"] == "none",
    "abstention": lambda row: row["abstention"],
}


def lexical_counts(chosen):
    done = [row for row in chosen if row["status"] == "measured"]
    return {"answers": len(done), "missing": len(chosen) - len(done),
            "declines": sum(1 for row in done if v5plan.is_decline(row["outcome"])),
            "false_declines": sum(1 for row in done if row["decline_class"] == "false_decline"),
            "ai_disclaimer": sum(1 for row in done if row["ai_disclaimer"]),
            "copied_header": sum(row["copied_header"] for row in done),
            "with_raw_event_ids": sum(1 for row in done if row["raw_event_ids"]),
            "self_contradiction": sum(1 for row in done if row["self_contradiction"]),
            "cited_labels": sum(row["cited_labels"] for row in done),
            "unresolved_labels": sum(row["unresolved_labels"] for row in done),
            "cites_gold_turn": sum(1 for row in done if row["cites_gold_turn"]),
            "contains_reference": sum(1 for row in done if row["contains_reference"]),
            "latex": sum(1 for row in done if row["latex"]),
            "median_words": statistics.median([row["answer_words"] for row in done]) if done else None}


def readers_of(rows):
    return [reader for reader in ["qwen-local", *READERS] if any(row["reader"] == reader for row in rows)]


def lexical_tables(rows):
    tables = {}
    for reader in readers_of(rows):
        mine = [row for row in rows if row["reader"] == reader and row["question_id"] not in EXCLUDED_FROM_COUNTS]
        tables[reader] = {}
        for cohort in COHORT_ORDER:
            subset = [row for row in mine if row["cohort"] == cohort]
            tables[reader][cohort] = {"all": lexical_counts(subset),
                                      **{name: lexical_counts([row for row in subset if test(row)])
                                         for name, test in SUBSETS.items()}}
    return tables


def repeatability(rows, key):
    """Per reader: questions with all samples present, and how many agree on `key` across samples."""
    out = {}
    for reader in readers_of(rows):
        groups = {}
        for row in rows:
            if row["reader"] == reader and row["question_id"] not in EXCLUDED_FROM_COUNTS:
                groups.setdefault((row["cohort"], row["question_id"]), []).append(row)
        complete = [group for group in groups.values() if all(row["status"] == "measured" for row in group)
                    and len(group) >= 2]
        out[reader] = {"questions": len(complete), "samples_per_question": sorted({len(group) for group in complete}),
                       "unanimous": sum(1 for group in complete if len({key(row) for row in group}) == 1)}
    return out


def operations(rows):
    out = {}
    for reader in readers_of(rows):
        mine = [row["record"] for row in rows if row["reader"] == reader]
        seconds = sorted(record["seconds"] for record in mine if record.get("seconds"))
        out[reader] = {"requests": len(mine),
                       "failures": sum(1 for record in mine if record.get("failure") not in (None, "incomplete_result")),
                       "incomplete": sum(1 for record in mine if record.get("failure") == "incomplete_result"),
                       "retried": sum(1 for record in mine if (record.get("tries") or 1) > 1),
                       "median_seconds": round(statistics.median(seconds), 2) if seconds else None,
                       "p90_seconds": round(seconds[int(0.9 * (len(seconds) - 1))], 2) if seconds else None,
                       "input_tokens": sum(record.get("input_tokens") or 0 for record in mine),
                       "output_tokens": sum(record.get("output_tokens") or 0 for record in mine),
                       "reasoning_tokens": sum(record.get("reasoning_tokens") or 0 for record in mine),
                       "usd": str(Decimal(sum(record.get("microusd") or 0 for record in mine)) / 10**6)}
    return out


def measure(args):
    output = args.output.absolute()
    _declaration, rows, _answered, _frozen, _sources = measure_rows(output, args.dataset, args.qwen_run)
    document = {"version": VERSION, "kind": "reader-comparison-measure", "recorded_at_utc": now(),
                "lexical": lexical_tables(rows),
                "repeatability": {"byte_identical": repeatability(rows, lambda row: row["answer_sha256"]),
                                  "decline_status": repeatability(rows, lambda row: v5plan.is_decline(row["outcome"]))},
                "operations": operations(rows),
                "excluded": {reader: [{key: row.get(key) for key in ("cohort", "replicate", "outcome", "decline_class")}
                                      for row in rows if row["reader"] == reader and row["question_id"] in EXCLUDED_FROM_COUNTS]
                             for reader in readers_of(rows)},
                "rows": [{key: value for key, value in row.items() if key != "record"} for row in rows]}
    replay.private_write(output / "measure.json", replay.canonical(document) + b"\n")
    print(json.dumps({key: document[key] for key in ("repeatability", "operations")}, indent=1))


