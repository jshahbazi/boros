# --------------------------------------------------------------------------- reference run

def reference_runs(reference: Path):
    """(cohort, question ID) -> (step 3 run index, declared entry) for the V4 arm."""
    declaration = json.loads((reference / "declaration.json").read_text())
    require(declaration.get("version") == v4v.VERSION, "reference_declaration_version")
    out = {}
    for index, entry in enumerate(declaration["runs"]):
        if entry["arm"] == "v4-default":
            out[(entry["cohort"], entry["question_id"])] = (index, entry)
    require(len(out) == 94, "reference_v4_runs_not_94")
    return declaration, out


def native_answer(output: Path, rows, index, ordinal):
    """(report, attempt item, answer text) of a finished local run, or Nones."""
    finished = [row for row in rows if row["run"] == index and row.get("invocation_started") is True]
    native = output / (finished[-1]["directory"] if finished else "missing")
    if not (native / "report.json").exists():
        return None, None, None
    report = json.loads((native / "report.json").read_text())
    item = [attempt for attempt in report["attempts"] if attempt["ordinal"] == ordinal][0]
    path = native / item["answer_file"]
    return report, item, (path.read_text() if path.exists() else None)


