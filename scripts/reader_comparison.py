def capture(args):
    """Offline: the exact V4 answer request body for each of the 94 step 3 V4 runs. No generation."""
    import retrieval_harness as harness
    output = args.output.absolute()
    require(output.is_relative_to(ROOT / ".build"), "output_outside_build")
    reference = args.reference.absolute()
    ref_declaration, ref_runs = reference_runs(reference)
    ref_ledger = replay.ledger(reference)
    plan = v4v.cohorts()
    frozen = v4v.frozen_inputs(args.dataset, plan)
    replay.private_directory(output)
    requests = output / "requests"
    replay.private_directory(requests)
    cache_root = output / "harness"
    replay.private_directory(cache_root)
    binary, implementation = harness.compile_harness(cache_root)
    endpoint = harness.OfflineEndpoint(args.tokenizer, 0).start()
    rows = []
    try:
        with tempfile.TemporaryDirectory(prefix="boros-reader-capture-", dir=output) as scratch_name:
            scratch = Path(scratch_name)
            os.chmod(scratch, 0o700)
            for cohort in COHORT_ORDER:
                cases, _arm = plan[cohort]
                for qid, run, strategy, _policy in cases:
                    index, entry = ref_runs[(cohort, qid)]
                    history, document, _ = frozen[(qid, run)]
                    require(v5plan.e_digest(document) == entry["runner_input_sha256"], "runner_input_mismatch")
                    arm = v4v.gold_arm(cohort, strategy)
                    require(arm == entry["declared_gold_arm"], "arm_mismatch")
                    directory = requests / case_name(cohort, qid)
                    require(not directory.exists(), "capture_exists")
                    replay.private_directory(directory)
                    hybrid = [attempt for attempt in document["attempts"] if attempt["strategy"] == "hybrid"][0]
                    configuration = dict(document["configuration"], endpoint=endpoint.url)
                    base = {"version": 1, "cache_directory": str(cache_root / "stores" / v5plan.e_digest(document)),
                            "events": document["events"], "configuration": configuration,
                            "question": {key: hybrid[key] for key in ("project_id", "conversation_key", "prompt",
                                                                      "question_time")},
                            "arms": [arm], "declared_source_ids": None, "capture_directory": str(directory)}
                    selection = harness.run_process(binary, "select", base, scratch, "capture")
                    item = (selection.get("attempts") or [{}])[0]
                    sizes = {event["id"]: len(event["text"].encode()) for event in document["events"]}
                    ranges = v5plan.delivered_ranges(item.get("recent_source_ids") or [], item.get("evidence") or [], sizes)
                    body_path = directory / (arm + ".request.json")
                    row = {"cohort": cohort, "question_id": qid, "arm": arm, "reference_run": index,
                           "runner_input_sha256": entry["runner_input_sha256"],
                           "process_failure": selection.get("process_failure"), "failure": item.get("failure"),
                           "preparation_completed": bool(item.get("preparation_completed")),
                           "runner_started": bool(item.get("runner_started")),
                           "context_framing": item.get("context_framing"),
                           "delivered_ranges_sha256": replay.ranges_digest(ranges),
                           "delivery_matches_reference": replay.ranges_digest(ranges)
                           == entry["declared_delivered_ranges_sha256"],
                           "harness_prompt_tokens": item.get("prompt_tokens"),
                           "request_sha256": item.get("request_sha256"), "request_bytes": item.get("request_bytes"),
                           "maximum_output": entry["maximum_output"], "question_type": entry["question_type"],
                           "abstention": entry["abstention"], "declared_gold_delivery": entry["declared_gold_delivery"],
                           "citation_labels": item.get("citation_labels")}
                    report, ref_item, _ = native_answer(reference, ref_ledger, index, entry["attempt"])
                    row["reference_prompt_tokens"] = ((ref_item or {}).get("provider_usage") or {}).get("promptTokens")
                    row["reference_label_map_equal"] = _labels(ref_item and ref_item.get("citation_labels")) \
                        == _labels(item.get("citation_labels"))
                    if body_path.exists():
                        raw = body_path.read_bytes()
                        row["body_digest_matches"] = replay.digest(raw) == item.get("request_sha256")
                        messages = request_messages(raw)
                        row["message_roles"] = [message["role"] for message in messages]
                        row["system_sha256"] = replay.digest(messages[0]["content"].encode()) \
                            if messages[0]["role"] == "system" else None
                    rows.append(row)
                    print(json.dumps({key: row.get(key) for key in ("cohort", "question_id", "failure",
                                      "delivery_matches_reference", "body_digest_matches", "harness_prompt_tokens",
                                      "reference_prompt_tokens")}), flush=True)
    finally:
        endpoint.stop()
    require(not any(row["runner_started"] for row in rows), "answer_runner_started")
    manifest = {"version": VERSION, "kind": "reader-comparison-captures", "recorded_at_utc": now(),
                "reference": {"path_name": reference.name, "declaration_sha256":
                              replay.digest((reference / "declaration.json").read_bytes()),
                              "binary_sha256": ref_declaration["binary"]["sha256"]},
                "harness": implementation, "endpoint_counters": endpoint.counters, "rows": rows,
                "summary": capture_summary(rows)}
    replay.private_write(output / "captures.json", replay.canonical(manifest) + b"\n")
    print(json.dumps({"captures": len(rows), **manifest["summary"],
                      "captures_sha256": replay.digest((output / "captures.json").read_bytes())}))


def _labels(value):
    return sorted((entry.get("label"), entry.get("event_id"), entry.get("kind")) for entry in value or [])


def capture_summary(rows):
    differences = [row["harness_prompt_tokens"] - row["reference_prompt_tokens"] for row in rows
                   if isinstance(row.get("harness_prompt_tokens"), int) and isinstance(row.get("reference_prompt_tokens"), int)]
    return {"complete": sum(1 for row in rows if row.get("body_digest_matches") and row["preparation_completed"]),
            "delivery_matches_reference": sum(1 for row in rows if row["delivery_matches_reference"]),
            "framing_v4": sum(1 for row in rows if row.get("context_framing") == V4),
            "label_map_equal": sum(1 for row in rows if row["reference_label_map_equal"]),
            "prompt_token_difference_min": min(differences) if differences else None,
            "prompt_token_difference_max": max(differences) if differences else None,
            "distinct_system_messages": len({row.get("system_sha256") for row in rows})}


def request_messages(raw: bytes):
    """The role messages of a captured OpenAI-style body, validated."""
    body = json.loads(raw)
    require(isinstance(body, dict) and isinstance(body.get("messages"), list) and body["messages"], "body_invalid")
    for message in body["messages"]:
        require(isinstance(message, dict) and set(message) == {"role", "content"}
                and message["role"] in ("system", "user", "assistant") and isinstance(message["content"], str),
                "body_messages_invalid")
    return body["messages"]


def load_captures(output: Path):
    manifest = json.loads((output / "captures.json").read_text())
    require(manifest.get("version") == VERSION, "captures_version")
    require(manifest["summary"]["complete"] == len(manifest["rows"]) == 94, "captures_incomplete")
    require(manifest["summary"]["delivery_matches_reference"] == 94 and manifest["summary"]["framing_v4"] == 94,
            "captures_do_not_match_reference")
    return manifest


def captured_body(output: Path, row):
    raw = (output / "requests" / case_name(row["cohort"], row["question_id"]) / (row["arm"] + ".request.json")).read_bytes()
    require(replay.digest(raw) == row["request_sha256"], "captured_body_changed")
    return request_messages(raw)


# --------------------------------------------------------------------------- provider calls

def max_output(model, row):
    reader = READERS[model]
    return row["maximum_output"] + (reader.get("thinking_allowance") or 0)


def generation_request(model, messages, row):
    reader = READERS[model]
    if reader["route"] == "anthropic":
        return va.generation_url(model=model), va.payload(messages, max_output(model, row), model=model,
                                                           thinking=reader["thinking"])
    return vg.generation_url(model), vg.payload(messages, max_output(model, row), thinking_level=reader["thinking_level"])


def count_request(model, messages):
    if READERS[model]["route"] == "anthropic":
        return va.count_url(), va.count_payload(messages, model=model)
    return vg.count_url(model), vg.count_payload(messages)


def send(model, url, body, token):
    return (va.post if READERS[model]["route"] == "anthropic" else vg.post)(url, body, token)


def parse(model, raw):
    """(text, usage, stop reason, failure). A response cut at the output limit keeps its text and is
    recorded as incomplete, as a local answer at its cap would be."""
    route = READERS[model]["route"]
    module = va if route == "anthropic" else vg
    metadata = module.response_metadata(raw)
    try:
        text, usage = module.parse_response(raw, model) if route == "gemini" else module.parse_response(raw, model=model)
        return text, usage, metadata["stop_reason"], None
    except va.VertexError as error:
        code = str(error)
        if code != "response_incomplete":
            return None, None, metadata["stop_reason"], code
    value = json.loads(raw)
    if route == "anthropic":
        text = "".join(block.get("text", "") for block in value.get("content") or [] if block.get("type") == "text")
        usage = va.parse_usage(value)
    else:
        parts = ((value.get("candidates") or [{}])[0].get("content") or {}).get("parts") or []
        text = "".join(part.get("text", "") for part in parts if part.get("thought") is not True)
        usage = vg.parse_usage(value)
    return text, usage, metadata["stop_reason"], "incomplete_result"


def pricing(model):
    return va.Pricing(READERS[model]["input_usd"], READERS[model]["output_usd"])


# --------------------------------------------------------------------------- count

def count(args):
    """Free token counts of every captured input on every reader's count endpoint."""
    output = args.output.absolute()
    manifest = load_captures(output)
    token = va.AccessTokens()
    rows = []
    for row in manifest["rows"]:
        messages = captured_body(output, row)
        for model in READERS:
            url, body = count_request(model, messages)
            raw = send(model, url, body, token())
            tokens = va.parse_count(raw) if READERS[model]["route"] == "anthropic" else vg.parse_count(raw)
            rows.append({"cohort": row["cohort"], "question_id": row["question_id"], "model": model,
                         "input_tokens": tokens, "max_output_tokens": max_output(model, row)})
    totals = {}
    for model in READERS:
        mine = [row for row in rows if row["model"] == model]
        price = pricing(model)
        worst = sum(price.microusd(row["input_tokens"], row["max_output_tokens"]) for row in mine) * REPLICATES
        totals[model] = {"input_tokens_per_pass": sum(row["input_tokens"] for row in mine),
                         "max_output_tokens_per_pass": sum(row["max_output_tokens"] for row in mine),
                         "worst_case_usd_all_replicates": str(Decimal(worst) / Decimal(10**6))}
    document = {"version": VERSION, "kind": "reader-comparison-counts", "recorded_at_utc": now(),
                "captures_sha256": replay.digest((output / "captures.json").read_bytes()), "rows": rows, "totals": totals}
    replay.private_write(output / "counts.json", replay.canonical(document) + b"\n")
    print(json.dumps({"counts": len(rows), "totals": totals}))


