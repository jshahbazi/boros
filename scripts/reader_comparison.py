def run(args):
    output = args.output.absolute()
    declaration = json.loads((output / "declaration.json").read_text())
    require(declaration.get("version") == VERSION, "declaration_version")
    manifest = load_captures(output)
    require(replay.digest((output / "captures.json").read_bytes()) == declaration["captures_sha256"], "captures_changed")
    counts_document = json.loads((output / "counts.json").read_text())
    require(replay.digest((output / "counts.json").read_bytes()) == declaration["counts_sha256"], "counts_changed")
    for name, value in declaration["drivers"].items():
        require(replay.digest((ROOT / "scripts" / name).read_bytes()) == value, "driver_changed")
    counted = {(row["model"], row["cohort"], row["question_id"]): row for row in counts_document["rows"]}
    rows = {(row["cohort"], row["question_id"]): row for row in manifest["rows"]}
    answers = output / "answers"
    replay.private_directory(answers)
    for model in READERS:
        replay.private_directory(answers / model)
    cap = Decimal(declaration["spending_cap_usd"]) * 10**6
    lock = threading.Lock()
    done = {}
    spent = 0
    for line in (output / "ledger.jsonl").read_text().splitlines():
        record = json.loads(line)
        if record["state"] == "finished":
            done[record["job"]] = record
            spent += record.get("microusd") or 0
    token = va.AccessTokens()
    state = {"spent": spent, "stopped": None}

    def append(record):
        with open(output / "ledger.jsonl", "a") as handle:
            handle.write(json.dumps(record, sort_keys=True) + "\n")

    def work(index):
        job = declaration["jobs"][index]
        model, row = job["model"], rows[(job["cohort"], job["question_id"])]
        price = pricing(model)
        worst = price.microusd(counted[(model, job["cohort"], job["question_id"])]["input_tokens"], max_output(model, row))
        with lock:
            if state["stopped"] or state["spent"] + worst > cap:
                state["stopped"] = state["stopped"] or "cap_reached"
                return
            state["spent"] += worst  # reserved; settled below
            append({"job": index, "state": "started", "at": now()})
        url, body = generation_request(model, captured_body(output, row), row)
        failure, raw, tries, started = None, None, 0, time.monotonic()
        while True:
            tries += 1
            started = time.monotonic()
            try:
                raw = send(model, url, body, token())
                failure = None
            except va.VertexError as error:
                failure = str(error)
            if failure in RETRYABLE and tries <= len(RETRY_DELAYS):
                time.sleep(RETRY_DELAYS[tries - 1])
                continue
            break
        seconds = time.monotonic() - started
        record = {"job": index, "state": "finished", "model": model, "cohort": job["cohort"],
                  "question_id": job["question_id"], "replicate": job["replicate"], "tries": tries,
                  "seconds": round(seconds, 3), "at": now()}
        microusd = 0
        if raw is not None:
            text, usage, stop, failure = parse(model, raw)
            replay.private_write(answers / (answer_name(model, job["cohort"], job["question_id"], job["replicate"])
                                            + ".response.json"), raw)
            if usage is not None:
                microusd = price.microusd(usage["input_tokens"], usage["output_tokens"])
                record.update(input_tokens=usage["input_tokens"], output_tokens=usage["output_tokens"],
                              reasoning_tokens=usage["reasoning_tokens"],
                              visible_output_upper_bound=usage["nonreasoning_output_upper_bound"])
            if text is not None:
                path = answers / (answer_name(model, job["cohort"], job["question_id"], job["replicate"]) + ".txt")
                replay.private_write(path, text.encode())
                record["answer_sha256"] = replay.digest(text.encode())
            record["stop_reason"] = stop
        record.update(failure=failure, microusd=microusd)
        with lock:
            state["spent"] += microusd - worst
            append(record)
            if failure not in (None, "incomplete_result") and failure.startswith("http_status_4") \
                    and failure != "http_status_429":
                state["stopped"] = "client_error_" + failure
        print(json.dumps({key: record.get(key) for key in ("job", "model", "cohort", "question_id", "replicate",
                                                          "failure", "seconds", "microusd")}), flush=True)

    pending = [index for index in range(len(declaration["jobs"])) if index not in done]
    with ThreadPoolExecutor(max_workers=declaration["workers"]) as pool:
        list(pool.map(work, pending))
    finished = [json.loads(line) for line in (output / "ledger.jsonl").read_text().splitlines()]
    finished = [record for record in finished if record["state"] == "finished"]
    print(json.dumps({"finished": len(finished), "jobs": len(declaration["jobs"]), "stopped": state["stopped"],
                      "spent_usd": str(Decimal(sum(record.get("microusd") or 0 for record in finished)) / 10**6),
                      "failures": sum(1 for record in finished if record.get("failure") not in (None,
                                                                                               "incomplete_result")),
                      "incomplete": sum(1 for record in finished if record.get("failure") == "incomplete_result")}))


