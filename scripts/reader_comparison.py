def jobs_for(manifest):
    """Dispatch order: replicate, then cohort and question as captured, then readers rotated by question."""
    jobs = []
    models = list(READERS)
    for replicate in range(REPLICATES):
        for position, row in enumerate(manifest["rows"]):
            shift = position % len(models)
            for model in models[shift:] + models[:shift]:
                jobs.append({"model": model, "cohort": row["cohort"], "question_id": row["question_id"],
                             "replicate": replicate})
    return jobs


